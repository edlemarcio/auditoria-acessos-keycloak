import { expect, test, type Locator, type Page } from '@playwright/test'
import { abrir, entrar, semViolacoes } from './ajuda'

/** Avança só com Tab até o elemento ficar com o foco (navegação só por teclado). */
async function tabAte(page: Page, alvo: Locator, max = 60) {
  for (let k = 0; k < max; k++) {
    if (await alvo.evaluate((el) => el === document.activeElement).catch(() => false)) return
    await page.keyboard.press('Tab')
  }
  throw new Error(`foco não chegou em ${alvo}`)
}

test.describe('jornadas só com teclado', () => {
  test('solicitante: pular para o conteúdo, pedir pelo assistente e acompanhar', async ({ page }) => {
    await entrar(page, 'solicitante')
    await abrir(page, '/')
    await page.keyboard.press('Tab')
    await expect(page.getByRole('link', { name: 'Ir para o conteúdo' })).toBeFocused()
    await tabAte(page, page.getByRole('link', { name: 'Nova solicitação' }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Nova solicitação', level: 1 })).toBeFocused()
    const cpf = page.getByRole('textbox', { name: 'CPF' })
    await tabAte(page, cpf)
    await page.keyboard.type('529.982.247-25')
    await page.keyboard.press('Tab')
    await expect(page.getByRole('textbox', { name: 'CPF' })).toHaveValue('***.982.247-**')
    await expect(page.locator('body')).not.toContainText('529.982.247-25')
    await tabAte(page, page.getByRole('button', { name: /Próximo/ }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: /Passo 2 de 5/ })).toBeFocused()
    await tabAte(page, page.getByRole('button', { name: 'Pedir preservação urgente' }))
    await page.keyboard.press('Space')
    await expect(page.getByRole('button', { name: 'Preservação urgente pedida' })).toBeVisible()
    await tabAte(page, page.getByRole('button', { name: /Próximo/ }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: /Passo 3 de 5/ })).toBeFocused()
    await tabAte(page, page.getByRole('button', { name: /Próximo/ }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: /Passo 4 de 5/ })).toBeFocused()
    await tabAte(page, page.getByRole('combobox', { name: /Tipo de processo/ }))
    await page.keyboard.press('ArrowDown')
    await tabAte(page, page.getByRole('textbox', { name: /Nº do processo/ }))
    await page.keyboard.type('0001234-12.2026.6.05.0000')
    await page.keyboard.press('Tab')
    await page.keyboard.type('Acessos fora do expediente ao sistema de pessoal')
    await tabAte(page, page.getByRole('button', { name: /Próximo/ }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: /Passo 5 de 5/ })).toBeFocused()
    await expect(page.getByText(/\d+ tarefas/)).toBeVisible()
    await tabAte(page, page.getByRole('button', { name: /Enviar pedido/ }))
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/\/investigacoes\/\d+$/)
    await expect(page.getByText('Pedido enviado para aprovação.')).toBeVisible()
    await expect(page.locator('.cabecalho-investigacao')).toContainText('Aguardando aprovação')
    expect(page.url()).not.toContain('52998224725')
    await semViolacoes(page, 'resumo depois do envio')
  })

  test('aprovador: fila → decisão → aprovar com step-up e retomada da ação', async ({ page }) => {
    await entrar(page, 'aprovador')   // sem step-up recente: a API pede e a tela volta
    await abrir(page, '/aprovacoes')
    const decidir = page.getByRole('link', { name: 'Decidir o pedido 139' })
    await tabAte(page, decidir)
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { level: 1 })).toContainText('investigação 39')
    await tabAte(page, page.getByRole('button', { name: 'Aprovar', exact: true }))
    await page.keyboard.press('Enter')
    const dialogo = page.getByRole('dialog', { name: /Aprovar · investigação 39/ })
    await expect(dialogo).toBeVisible()
    await expect(page.getByRole('textbox', { name: /Investigador designado/ })).toBeFocused()
    await page.keyboard.type('investigador2')
    await page.keyboard.press('Tab')
    await page.keyboard.press('Tab')
    await page.keyboard.type('Pedido completo e com fundamento')
    await tabAte(page, page.getByRole('button', { name: /Confirmar: aprovar/ }))
    await page.keyboard.press('Enter')
    // step-up: foi ao /auth/entrar?step_up=1 e voltou para a mesma tela, com o diálogo reaberto
    await expect(page).toHaveURL(/\/aprovacoes\/139\?inv=39/)
    await expect(page.getByText('Identidade confirmada. Revise e confirme a ação de novo.')).toBeVisible()
    await expect(page.getByRole('textbox', { name: /Investigador designado/ })).toHaveValue('')
    await page.getByRole('textbox', { name: /Investigador designado/ }).fill('investigador1')
    await page.getByRole('textbox', { name: /Motivo/ }).fill('Pedido completo e com fundamento')
    await page.getByRole('textbox', { name: /Motivo/ }).press('Tab')
    await tabAte(page, page.getByRole('button', { name: /Confirmar: aprovar/ }))
    await page.keyboard.press('Enter')
    await expect(page.getByText(/Pedido aprovado e investigador investigador1 designado/)).toBeVisible()
    await expect(page.getByText('Não há decisão sua pendente')).toBeVisible()
  })

  test('aprovador: devolver e recusar pedem motivo; Esc fecha o diálogo e devolve o foco', async ({ page }) => {
    await entrar(page, 'aprovador', 'claro', true)
    await abrir(page, '/aprovacoes/140?inv=40&tipo=preservacao_urgente')
    const devolver = page.getByRole('button', { name: 'Devolver para correção' })
    await tabAte(page, devolver)
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog')).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('dialog')).toBeHidden()
    await expect(devolver).toBeFocused()
    await page.keyboard.press('Enter')
    await tabAte(page, page.getByRole('button', { name: /Confirmar: devolver/ }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('dialog').getByText(/Escreva o motivo/).first()).toBeVisible()
    await page.getByRole('textbox', { name: /Motivo/ }).fill('Falta o número do processo disciplinar')
    await page.keyboard.press('Tab')
    await tabAte(page, page.getByRole('button', { name: /Confirmar: devolver/ }))
    await page.keyboard.press('Enter')
    await expect(page.getByText(/Devolver para correção: feito/)).toBeVisible()
  })

  test('aprovador: autorizar preservação urgente (coleta lacrada)', async ({ page }) => {
    await entrar(page, 'aprovador', 'claro', true)
    await abrir(page, '/aprovacoes/140?inv=40&tipo=preservacao_urgente')
    await tabAte(page, page.getByRole('button', { name: 'Autorizar preservação urgente' }))
    await page.keyboard.press('Enter')
    await page.keyboard.type('investigador1')
    await page.getByRole('textbox', { name: /Motivo/ }).fill('Eventos expiram em 2 dias')
    await page.getByRole('button', { name: /Confirmar: autorizar/ }).focus()
    await page.keyboard.press('Enter')
    await expect(page.getByText(/Preservação urgente autorizada/)).toBeVisible()
    await expect(page.getByText('Coleta lacrada em andamento.')).toBeVisible()
  })

  test('aprovador: pacote sem máscara decidido com motivo', async ({ page }) => {
    await entrar(page, 'aprovador', 'claro', true)
    await abrir(page, '/aprovacoes/77?inv=33&tipo=pacote_sem_mascara')
    await expect(page.getByText(/Promotoria Eleitoral/)).toBeVisible()
    await tabAte(page, page.getByRole('textbox', { name: /Motivo da decisão/ }))
    await page.keyboard.type('Requisição com fundamento e destinatário competente')
    await page.keyboard.press('Tab')
    await expect(page.getByRole('button', { name: /Aprovar pacote sem máscara/ })).toBeFocused()
    await page.keyboard.press('Enter')
    await expect(page.getByText(/Pacote sem máscara aprovado/)).toBeVisible()
  })

  test('investigador: iniciar, pausar e retomar com o acompanhamento ao vivo e reconexão', async ({ page }) => {
    await entrar(page, 'investigador')
    await abrir(page, '/investigacoes/35')
    await tabAte(page, page.getByRole('button', { name: 'Iniciar coleta' }))
    await page.keyboard.press('Enter')
    await expect(page.locator('.cabecalho-investigacao')).toContainText(/Coletando/)
    const acomp = page.locator('.acompanhamento')
    await expect(acomp).toContainText('Ao vivo')
    // o dublê derruba a conexão a cada 6 eventos: aparece "Reconectando…" e o progresso continua de onde parou
    await expect(acomp).toContainText('Reconectando…', { timeout: 15_000 })
    await expect(acomp).toContainText('Ao vivo', { timeout: 15_000 })
    const pct = Number((await acomp.locator('.kpi-valor').first().textContent())!.replace('%', ''))
    expect(pct).toBeGreaterThanOrEqual(6)
    await tabAte(page, page.getByRole('button', { name: 'Pausar' }))
    await page.keyboard.press('Enter')
    await expect(page.locator('.cabecalho-investigacao')).toContainText('Pausada')
    await tabAte(page, page.getByRole('button', { name: 'Retomar' }))
    await page.keyboard.press('Enter')
    await expect(page.locator('.cabecalho-investigacao')).toContainText(/Coletando/)
  })

  test('investigador: pacote mascarado e link de uso único; pacote expirado avisa', async ({ page }) => {
    await entrar(page, 'investigador')
    await abrir(page, '/investigacoes/33/pacotes')
    await expect(page.getByText(/ficou disponível por 24 h e foi apagado/)).toBeVisible()
    await tabAte(page, page.getByRole('button', { name: 'Gerar link de download do pacote 7' }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('link', { name: 'Baixar pacote 7' })).toBeVisible()
    await expect(page.getByText(/uso único/)).toBeVisible()
    await tabAte(page, page.getByRole('button', { name: 'Gerar pacote mascarado' }))
    await page.keyboard.press('Enter')
    await expect(page.getByText(/Pacote mascarado pedido/)).toBeVisible()
  })

  test('sem acesso: pedir acesso ao aprovador', async ({ page }) => {
    await entrar(page, 'solicitante')
    await page.goto('/investigacoes/4242')
    await expect(page.getByRole('heading', { name: 'Você não tem acesso a esta investigação' })).toBeVisible()
    await tabAte(page, page.getByRole('button', { name: 'Pedir acesso ao aprovador' }))
    await page.keyboard.press('Enter')
    await page.keyboard.type('Sou da comissão do processo disciplinar')
    await page.keyboard.press('Tab')
    await page.keyboard.press('Enter')
    await expect(page.getByText('Pedido de acesso registrado.')).toBeVisible()
  })

  test('celular (390 px): menu recolhido abre pelo teclado e leva às aprovações', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 })
    await entrar(page, 'aprovador')
    await abrir(page, '/')
    const botao = page.getByRole('button', { name: 'Abrir menu' })
    await tabAte(page, botao)
    await page.keyboard.press('Enter')
    await tabAte(page, page.getByRole('navigation', { name: 'Navegação principal' }).getByRole('link', { name: 'Aprovações' }))
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Aprovações', level: 1 })).toBeFocused()
    await semViolacoes(page, 'aprovações no celular')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
  })

  test('menu: itens sem permissão não aparecem; admin não vê Investigações', async ({ page }) => {
    await entrar(page, 'admin_tecnico')
    await abrir(page, '/')
    const nav = page.getByRole('navigation', { name: 'Navegação principal' })
    await expect(nav.getByRole('link')).toHaveText(['Início', 'Administração'])
  })

  test('notificações pelo teclado: abrir, marcar todas, Esc fecha', async ({ page }) => {
    await entrar(page, 'solicitante')
    await abrir(page, '/')
    const sino = page.getByRole('button', { name: /Notificações: 2 não lidas/ })
    await tabAte(page, sino)
    await page.keyboard.press('Enter')
    await expect(page.getByRole('heading', { name: 'Notificações' })).toBeFocused()
    await page.keyboard.press('Tab')
    await page.keyboard.press('Enter')
    await expect(page.getByRole('button', { name: 'Notificações: nenhuma não lida' })).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(page.getByRole('region', { name: 'Central de notificações' })).toBeHidden()
  })

  test('sessão expirada no meio do uso: aviso e volta para a mesma tela', async ({ page }) => {
    await entrar(page, 'solicitante')
    await abrir(page, '/investigacoes?visao=minhas')
    await page.context().clearCookies()
    await page.getByRole('button', { name: 'Todas' }).click()
    await expect(page.getByRole('heading', { name: 'Sua sessão expirou' })).toBeVisible()
    await page.getByRole('link', { name: /Entrar de novo/ }).click()
    await expect(page).toHaveURL(/\/investigacoes/)
    await expect(page.getByRole('heading', { name: 'Investigações', level: 1 })).toBeVisible()
  })
})
